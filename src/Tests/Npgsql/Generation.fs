// Read-only detection, from a column's pg_attribute row: (attgenerated, attidentity).

[<TestCase("s", "", true, Description = "GENERATED ALWAYS AS (...) STORED")>]
[<TestCase("v", "", true, Description = "GENERATED ALWAYS AS (...) VIRTUAL (PG18+)")>]
[<TestCase("", "a", true, Description = "GENERATED ALWAYS AS IDENTITY")>]
[<TestCase("", "d", false, Description = "GENERATED BY DEFAULT AS IDENTITY is writable")>]
[<TestCase("", "", false, Description = "an ordinary column")>]
let ``A column is read-only when the database generates it, and BY DEFAULT identity does not count`` attgenerated attidentity expected =
    let att : NpgsqlSchemaProvider.PgAttribute = { AttGenerated = attgenerated; AttIdentity = attidentity }
    NpgsqlSchemaProvider.isDatabaseGenerated att =! expected

// Read-only column generation. DB-free: drives SchemaTemplate.generate with a synthetic schema.

let private baseCfg : Config =
    {
        ConnectionString = ""
        OutputFile = ""
        Namespace = "TestNS"
        IsCLIMutable = true
        IsMutableProperties = false
        NullablePropertyType = NullablePropertyType.Option
        ProviderDbTypeAttributes = true
        TableDeclarations = true
        Readers = None
        Filters = Filters.Empty
        TypeMappingExtensions = []
    }

let private currencycode =
    {
        Column.Name = "currencycode"
        Column.IsNullable = false
        Column.IsPK = true
        Column.IsReadOnly = false
        Column.TypeMapping =
            {
                TypeMapping.ColumnTypeAlias = "character"
                TypeMapping.ClrType = "string"
                TypeMapping.DbType = System.Data.DbType.String
                TypeMapping.ProviderDbType = Some "Char"
            }
    }

/// A `GENERATED ALWAYS AS (...) STORED` column, as the schema provider marks it.
let private generatedRate =
    { currencycode with
        Column.Name = "rate"
        Column.IsPK = false
        Column.IsReadOnly = true
        Column.TypeMapping =
            {
                TypeMapping.ColumnTypeAlias = "numeric"
                TypeMapping.ClrType = "decimal"
                TypeMapping.DbType = System.Data.DbType.Decimal
                TypeMapping.ProviderDbType = Some "Numeric"
            } }

let private generateColumns columns =
    let schema : Schema =
        {
            Tables =
                [ {
                    Table.Catalog = ""
                    Table.Schema = "sales"
                    Table.Name = "currency"
                    Table.Type = TableType.Table
                    Table.Columns = currencycode :: columns
                    Table.TotalColumns = 1 + List.length columns
                  } ]
            Enums = []
        }

    let version : Version.InformationalVersion =
        { InformationalVersion = "4.1.0-test"; Version = System.Version(4, 1, 0); PreReleaseSuffix = None }

    SchemaTemplate.generate baseCfg Provider.instance schema version []

[<Test>]
let ``A generated column is marked read-only in the generated record``() =
    let code = generateColumns [ generatedRate ]
    code.Contains("[<ReadOnlyColumn>]") =! true
    code.Contains("rate: decimal") =! true

[<Test>]
let ``An ordinary column carries no attribute``() =
    (generateColumns []).Contains("[<ReadOnlyColumn>]") =! false

// Read-only detection against a live PostgreSQL: the four column kinds in one table.

let private readOnlyProbeDdl =
    """
    DROP TABLE IF EXISTS sales.sqlhydra_readonly_probe;
    CREATE TABLE sales.sqlhydra_readonly_probe (
        id    int GENERATED ALWAYS AS IDENTITY,
        seq   int GENERATED BY DEFAULT AS IDENTITY,
        price numeric NOT NULL,
        tax   numeric GENERATED ALWAYS AS (price * 0.1) STORED
    );
    """

let private execute sql =
    use conn = new global.Npgsql.NpgsqlConnection(DB.connectionString)
    conn.Open()
    use cmd = new global.Npgsql.NpgsqlCommand(sql, conn)
    cmd.ExecuteNonQuery() |> ignore

[<Test>]
let ``The schema provider marks the columns PostgreSQL generates, and only those``() =
    execute readOnlyProbeDdl

    try
        let cfg =
            { baseCfg with
                ConnectionString = DB.connectionString
                Filters = { Filters.Empty with Includes = [ "sales/sqlhydra_readonly_probe" ] } }

        // By name, not `exactlyOne`: materialized views are appended after the include filter.
        let isReadOnly =
            (NpgsqlSchemaProvider.getSchema(cfg, false, [])).Tables
            |> List.find (fun tbl -> tbl.Name = "sqlhydra_readonly_probe")
            |> fun tbl -> tbl.Columns |> List.map (fun col -> col.Name, col.IsReadOnly) |> Map.ofList

        isReadOnly["id"] =! true     // GENERATED ALWAYS AS IDENTITY
        isReadOnly["tax"] =! true    // GENERATED ALWAYS AS (...) STORED
        isReadOnly["seq"] =! false   // GENERATED BY DEFAULT AS IDENTITY: writable
        isReadOnly["price"] =! false
    finally
        execute "DROP TABLE IF EXISTS sales.sqlhydra_readonly_probe;"

let private crossTableProbeDdl =
    """
    DROP TABLE IF EXISTS sales.sqlhydra_generated_probe;
    DROP TABLE IF EXISTS sales.sqlhydra_ordinary_probe;
    DROP TABLE IF EXISTS person.sqlhydra_generated_probe;
    CREATE TABLE sales.sqlhydra_generated_probe (
        price numeric NOT NULL,
        tax   numeric GENERATED ALWAYS AS (price * 0.1) STORED
    );
    CREATE TABLE sales.sqlhydra_ordinary_probe (
        tax numeric NOT NULL
    );
    -- the generated table's name and column name, in another schema
    CREATE TABLE person.sqlhydra_generated_probe (
        tax numeric NOT NULL
    );
    """

let private dropCrossTableProbes =
    "DROP TABLE IF EXISTS sales.sqlhydra_generated_probe;
     DROP TABLE IF EXISTS sales.sqlhydra_ordinary_probe;
     DROP TABLE IF EXISTS person.sqlhydra_generated_probe;"

[<Test>]
let ``A generated column marks its own table and schema, not a same-named column elsewhere``() =
    // Drop either component from the lookup key and one of these writable `tax` columns
    // silently stops being written.
    execute crossTableProbeDdl

    try
        let cfg =
            { baseCfg with
                ConnectionString = DB.connectionString
                Filters =
                    { Filters.Empty with
                        Includes =
                            [ "sales/sqlhydra_generated_probe"
                              "sales/sqlhydra_ordinary_probe"
                              "person/sqlhydra_generated_probe" ] } }

        let tables = (NpgsqlSchemaProvider.getSchema(cfg, false, [])).Tables

        // A swapped argument here makes `List.find` throw, so it fails loudly, not silently.
        let isReadOnly schema table column =
            tables
            |> List.find (fun tbl -> tbl.Schema = schema && tbl.Name = table)
            |> fun tbl -> (tbl.Columns |> List.find (fun col -> col.Name = column)).IsReadOnly

        isReadOnly "sales" "sqlhydra_generated_probe" "tax" =! true
        // Same schema, different table.
        isReadOnly "sales" "sqlhydra_ordinary_probe" "tax" =! false
        // Same table and column name, different schema.
        isReadOnly "person" "sqlhydra_generated_probe" "tax" =! false
    finally
        execute dropCrossTableProbes

// A column of a view that cannot carry a write is the second thing that makes a column
// read-only, and it has nothing to do with generation.

[<TestCase(false, false, true, Description = "an expression or aggregate column of a plain view")>]
[<TestCase(true, false, false, Description = "a column an auto-updatable view passes straight through")>]
[<TestCase(false, true, false, Description = "an INSTEAD OF trigger takes the whole row, column answer or not")>]
[<TestCase(true, true, false, Description = "writable twice over")>]
let ``A view column is read-only only when nothing can carry a write to it`` columnIsUpdatable insteadOfTriggerWrites expected =
    let updatability : NpgsqlSchemaProvider.PgUpdatability =
        { ColumnIsUpdatable = columnIsUpdatable; InsteadOfTriggerWrites = insteadOfTriggerWrites }
    NpgsqlSchemaProvider.isViewColumnUnwritable updatability =! expected

let private viewProbeDdl =
    """
    DROP VIEW IF EXISTS sales.sqlhydra_trigger_view_probe CASCADE;
    DROP VIEW IF EXISTS sales.sqlhydra_aggregate_view_probe CASCADE;
    DROP VIEW IF EXISTS sales.sqlhydra_expression_view_probe CASCADE;
    DROP TABLE IF EXISTS sales.sqlhydra_view_base_probe CASCADE;
    DROP FUNCTION IF EXISTS sales.sqlhydra_view_probe_fn() CASCADE;

    CREATE TABLE sales.sqlhydra_view_base_probe (price numeric NOT NULL);

    -- auto-updatable but for the one column that is an expression
    CREATE VIEW sales.sqlhydra_expression_view_probe AS
        SELECT price, price * 2 AS doubled FROM sales.sqlhydra_view_base_probe;

    -- not auto-updatable in any column
    CREATE VIEW sales.sqlhydra_aggregate_view_probe AS
        SELECT count(*) AS row_count, sum(price) AS total FROM sales.sqlhydra_view_base_probe;

    -- the same shape, made writable again by INSTEAD OF triggers
    CREATE VIEW sales.sqlhydra_trigger_view_probe AS
        SELECT count(*) AS row_count, sum(price) AS total FROM sales.sqlhydra_view_base_probe;
    CREATE FUNCTION sales.sqlhydra_view_probe_fn() RETURNS trigger LANGUAGE plpgsql AS
        $$ BEGIN RETURN NEW; END; $$;
    CREATE TRIGGER sqlhydra_view_probe_insert INSTEAD OF INSERT ON sales.sqlhydra_trigger_view_probe
        FOR EACH ROW EXECUTE FUNCTION sales.sqlhydra_view_probe_fn();
    CREATE TRIGGER sqlhydra_view_probe_update INSTEAD OF UPDATE ON sales.sqlhydra_trigger_view_probe
        FOR EACH ROW EXECUTE FUNCTION sales.sqlhydra_view_probe_fn();
    """

let private dropViewProbes =
    "DROP VIEW IF EXISTS sales.sqlhydra_trigger_view_probe CASCADE;
     DROP VIEW IF EXISTS sales.sqlhydra_aggregate_view_probe CASCADE;
     DROP VIEW IF EXISTS sales.sqlhydra_expression_view_probe CASCADE;
     DROP TABLE IF EXISTS sales.sqlhydra_view_base_probe CASCADE;
     DROP FUNCTION IF EXISTS sales.sqlhydra_view_probe_fn() CASCADE;"

/// Read-only, by view name and column name. A swapped argument makes `List.find` throw,
/// so a mixed-up probe fails loudly rather than asserting against the wrong view.
let private readOnlyViewColumns () =
    let cfg =
        { baseCfg with
            ConnectionString = DB.connectionString
            Filters =
                { Filters.Empty with
                    Includes =
                        [ "sales/sqlhydra_expression_view_probe"
                          "sales/sqlhydra_aggregate_view_probe"
                          "sales/sqlhydra_trigger_view_probe" ] } }

    let tables = (NpgsqlSchemaProvider.getSchema(cfg, false, [])).Tables

    fun view column ->
        tables
        |> List.find (fun tbl -> tbl.Name = view)
        |> fun tbl -> (tbl.Columns |> List.find (fun col -> col.Name = column)).IsReadOnly

[<Test>]
let ``A view column no write can reach is read-only, and its neighbours are not``() =
    execute viewProbeDdl

    try
        let isReadOnly = readOnlyViewColumns ()
        isReadOnly "sqlhydra_expression_view_probe" "doubled" =! true
        isReadOnly "sqlhydra_expression_view_probe" "price" =! false
    finally
        execute dropViewProbes

[<Test>]
let ``An INSTEAD OF trigger keeps every column of its view writable``() =
    // The trigger is handed the whole row, so it is the one thing that makes a view of this
    // shape writable. Marking these read-only drops both columns from the INSERT the trigger
    // exists to receive.
    execute viewProbeDdl

    try
        let isReadOnly = readOnlyViewColumns ()
        isReadOnly "sqlhydra_trigger_view_probe" "row_count" =! false
        isReadOnly "sqlhydra_trigger_view_probe" "total" =! false
        // The same shape without the triggers: nothing can carry the write.
        isReadOnly "sqlhydra_aggregate_view_probe" "row_count" =! true
        isReadOnly "sqlhydra_aggregate_view_probe" "total" =! true
    finally
        execute dropViewProbes
