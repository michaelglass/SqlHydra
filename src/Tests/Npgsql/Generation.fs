// Read-only column generation. DB-free: drives SchemaTemplate.generate with a synthetic schema.

let private baseCfg : Config =
    {
        ConnectionString = ""
        OutputFile = ""
        Namespace = "TestNS"
        IsCLIMutable = true
        IsMutableProperties = false
        NullablePropertyType = NullablePropertyType.Option
        ProviderDbTypeAttributes = true
        TableDeclarations = true
        SystemColumns = []
        Readers = None
        Filters = Filters.Empty
        TypeMappingExtensions = []
    }

let private currencycode =
    {
        Column.Name = "currencycode"
        Column.IsNullable = false
        Column.IsPK = true
        Column.Doc = []
        Column.ReadOnly = None
        Column.TypeMapping =
            {
                TypeMapping.ColumnTypeAlias = "character"
                TypeMapping.ClrType = "string"
                TypeMapping.DbType = System.Data.DbType.String
                TypeMapping.ProviderDbType = Some "Char"
            }
    }

/// Stands in for a `GENERATED ALWAYS AS (...) STORED` column as the schema provider marks it.
let private generatedRate =
    {
        Column.Name = "rate"
        Column.IsNullable = false
        Column.IsPK = false
        Column.Doc = []
        Column.ReadOnly = Some ReadOnlyColumn.Generated
        Column.TypeMapping =
            {
                TypeMapping.ColumnTypeAlias = "numeric"
                TypeMapping.ClrType = "decimal"
                TypeMapping.DbType = System.Data.DbType.Decimal
                TypeMapping.ProviderDbType = Some "Numeric"
            }
    }

let private schemaOf columns : Schema =
    {
        Tables =
            [ {
                Table.Catalog = ""
                Table.Schema = "sales"
                Table.Name = "currency"
                Table.Type = TableType.Table
                Table.Columns = currencycode :: columns
                Table.TotalColumns = 1 + List.length columns
              } ]
        Enums = []
    }

let private generateColumns columns =
    let version : Version.InformationalVersion =
        { InformationalVersion = "4.1.0-test"; Version = System.Version(4, 1, 0); PreReleaseSuffix = None }
    SchemaTemplate.generate baseCfg Provider.instance (schemaOf columns) version []

let private generateWith systemColumns =
    generateColumns (systemColumns |> List.map NpgsqlDataTypes.toSystemColumn)

