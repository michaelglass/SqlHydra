// Read-only detection against a live PostgreSQL: the four column kinds in one table.

let private readOnlyProbeDdl =
    """
    DROP TABLE IF EXISTS sales.sqlhydra_readonly_probe;
    CREATE TABLE sales.sqlhydra_readonly_probe (
        id    int GENERATED ALWAYS AS IDENTITY,
        seq   int GENERATED BY DEFAULT AS IDENTITY,
        price numeric NOT NULL,
        tax   numeric GENERATED ALWAYS AS (price * 0.1) STORED
    );
    """

let private execute sql =
    use conn = new global.Npgsql.NpgsqlConnection(DB.connectionString)
    conn.Open()
    use cmd = new global.Npgsql.NpgsqlCommand(sql, conn)
    cmd.ExecuteNonQuery() |> ignore

[<Test>]
let ``The schema provider marks the columns PostgreSQL generates, and only those``() =
    execute readOnlyProbeDdl

    try
        let cfg =
            { baseCfg with
                ConnectionString = DB.connectionString
                Filters = { Filters.Empty with Includes = [ "sales/sqlhydra_readonly_probe" ] } }

        // Found by name, not `exactlyOne`: materialized views are appended after
        // `SchemaFilters.filterTables` runs, so the include filter does not narrow them.
        let isReadOnly =
            (NpgsqlSchemaProvider.getSchema(cfg, false, [])).Tables
            |> List.find (fun tbl -> tbl.Name = "sqlhydra_readonly_probe")
            |> fun tbl -> tbl.Columns |> List.map (fun col -> col.Name, col.ReadOnly.IsSome) |> Map.ofList

        isReadOnly["id"] =! true     // GENERATED ALWAYS AS IDENTITY
        isReadOnly["tax"] =! true    // GENERATED ALWAYS AS (...) STORED
        isReadOnly["seq"] =! false   // GENERATED BY DEFAULT AS IDENTITY: writable
        isReadOnly["price"] =! false
    finally
        execute "DROP TABLE IF EXISTS sales.sqlhydra_readonly_probe;"

